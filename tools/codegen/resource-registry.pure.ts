// The Resource record registry (GLOSSARY): what `npm run registry` writes from the Resource files. A Resource's record is
// its file, `src/content-store/resources/<slug>.ts`; its composition is the folder `src/episodes/resources/<slug>/`, which
// the Episode registry lists as `RESOURCE_SLUGS`. The generated map is typed against that list, so a record without a
// composition, or a composition without a record, fails `tsc`; the store refuses both again at load (design-ADR 0019).
// The file is checked in, and a fast test fails when it is stale. The disk side lives in registry.ts.

import type { RegistryFile } from './episode-registry.pure.ts';

/** Where the Resource registry lives. */
export const RESOURCE_REGISTRY_PATH = 'src/content-store/resource-registry.generated.ts';

const HEADER = [
  '// The Resource registry, generated by `npm run registry` from the Resource files: never edit by hand. A file',
  '// `src/content-store/resources/<slug>.ts` is a Resource record, named after its slug.',
].join('\n');

/** A slug as a record's `slug` field allows: lowercase words joined by hyphens. */
const SLUG = /^[a-z0-9]+(-[a-z0-9]+)*$/;

/** The identifier a slug is imported under: `context-window` -> `contextWindow`. */
function identifierOf(slug: string): string {
  const camel = slug.replace(/-([a-z0-9])/g, (_, next: string) => next.toUpperCase());
  return /^[0-9]/.test(camel) ? `_${camel}` : camel;
}

/** The Resource slugs the files name, in code-point order, so the registry is the same on every machine. */
function slugsOf(files: readonly string[]): string[] {
  const records = files.filter((file) => file.endsWith('.ts') && !file.endsWith('.test.ts'));
  const misnamed = records.filter((file) => !SLUG.test(file.slice(0, -'.ts'.length)));
  if (misnamed.length > 0)
    throw new Error(`A Resource file is named after its slug, <slug>.ts; rename ${misnamed.join(', ')}`);
  return records.map((file) => file.slice(0, -'.ts'.length)).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** The Resource registry for the given entries of `src/content-store/resources/`. */
export function resourceRegistryFile(files: readonly string[]): RegistryFile {
  const slugs = slugsOf(files);
  const imports = slugs.map((slug) => `import { resource as ${identifierOf(slug)} } from './resources/${slug}';`);
  const entries = slugs.map((slug) => `  '${slug}': ${identifierOf(slug)},`);
  const text = `${HEADER}
import type { ResourceSlug } from '@/content-store/catalogue/record-routes';
${imports.join('\n')}
import type { ResourceInput } from './schemas/resource.schema';

/** Every Resource record by slug, so a key and its record's slug must match, and every composition has one. */
export const RESOURCE_RECORDS = {
${entries.join('\n')}
} as const satisfies { readonly [S in ResourceSlug]: ResourceInput & { readonly slug: S } };
`;
  return { path: RESOURCE_REGISTRY_PATH, text };
}
